// covers: ["ADP-006", "ADP-017", "ADP-063"]
import { expect, it } from "vitest"
import type { Message } from "@earendil-works/pi-ai"
import { defaultSettings } from "@coool/adaptive-core/state/settings/parse"
import { proposalModels } from "../src/host/inventory.js"
import { prepareAdmission, virtualModels } from "../src/host/routing.js"
import { proposeTiers } from "../src/ui/proposal.js"
import { routingFixture } from "./routing-fixture.js"

it("dispatches configured thinking variants through the publicly registered route", async () => {
  const f = routingFixture({
    ...defaultSettings(),
    tiers: {
      quick: [],
      standard: [{ providerID: "local", id: "a", variant: "high" }],
      advanced: [],
    },
  })
  const ctx = {
    modelRegistry: { getAvailable: () => f.faux.models },
    sessionManager: { getBranch: () => [] },
  }
  const prepared = await prepareAdmission(
    "auto",
    { model: f.a, reason: "user", thinkingLevel: "off", messages: [] },
    ctx,
    f.sources,
    () => [],
  )
  expect((await prepared.choose()).decision).toMatchObject({
    kind: "apply",
    model: { variant: "high" },
  })
  const result = await f.route()(
    { model: f.a, reason: "user", thinkingLevel: "off", messages: [] },
    ctx,
  )
  expect(result).toMatchObject({ model: { id: "a" }, thinkingLevel: "high" })
})

it("retains the physical variant through tool continuations instead of reapplying virtual thinking", async () => {
  const f = routingFixture({
    ...defaultSettings(),
    tiers: { quick: [], standard: [{ providerID: "local", id: "b" }], advanced: [] },
  })
  const result = await f.route()(
    {
      model: f.a,
      reason: "continuation",
      thinkingLevel: "off",
      messages: [],
      previous: { model: f.a, thinkingLevel: "high" },
    },
    {
      modelRegistry: { getAvailable: () => f.faux.models },
      sessionManager: { getBranch: () => [] },
    },
  )
  expect(result).toMatchObject({ model: { id: "a" }, thinkingLevel: "high" })
})

it("gates variants for tools, context and images, and never treats an unsupported variant as its base", async () => {
  for (const scenario of ["tools", "context", "images", "variant"] as const) {
    const f = routingFixture({
      ...defaultSettings(),
      tiers: {
        quick: [],
        standard: [
          { providerID: "local", id: "a", variant: scenario === "variant" ? "imaginary" : "high" },
        ],
        advanced: [],
      },
    })
    const [route] = virtualModels(f.sources, () => (scenario === "tools" ? ["read"] : []))
    if (route === undefined) throw new Error("missing route")
    const messages: Message[] = []
    if (scenario === "context")
      messages.push({ role: "user", timestamp: 0, content: "x".repeat(1000) })
    if (scenario === "images")
      messages.push({
        role: "user",
        timestamp: 0,
        content: [{ type: "image", data: "AA==", mimeType: "image/png" }],
      })
    await expect(
      route.route(
        {
          model: f.a,
          reason: "user",
          thinkingLevel: "off",
          messages,
        },
        {
          modelRegistry: {
            getAvailable: () =>
              f.faux.models.map((model) => ({
                ...model,
                input: ["text"],
                contextWindow: scenario === "context" ? 1 : 100_000,
              })),
          },
          sessionManager: { getBranch: () => [] },
        },
      ),
    ).rejects.toThrow("no-compatible-resource")
  }
})

it("resolves compatible exact variants in defer fallback, and clamps variantless dispatch", async () => {
  const f = routingFixture({
    ...defaultSettings(),
    pin: { providerID: "local", id: "missing" },
    tiers: {
      quick: [],
      standard: [
        { providerID: "local", id: "a", variant: "imaginary" },
        { providerID: "local", id: "a", variant: "high" },
      ],
      advanced: [],
    },
  })
  const ctx = {
    modelRegistry: { getAvailable: () => f.faux.models },
    sessionManager: { getBranch: () => [] },
  }
  expect(
    await f.route()({ model: f.a, reason: "user", thinkingLevel: "off", messages: [] }, ctx),
  ).toMatchObject({ thinkingLevel: "high" })
  const plain = routingFixture({
    ...defaultSettings(),
    tiers: { quick: [], standard: [{ providerID: "local", id: "a" }], advanced: [] },
  })
  expect(
    await plain.route()(
      { model: plain.a, reason: "user", thinkingLevel: "high", messages: [] },
      {
        ...ctx,
        modelRegistry: {
          getAvailable: () => plain.faux.models.map((model) => ({ ...model, reasoning: false })),
        },
      },
    ),
  ).toMatchObject({ thinkingLevel: "off" })
})

it("dispatches the high variant generated by onboarding", async () => {
  const models = routingFixture().faux.models
  const tiers = proposeTiers(proposalModels([...models, { ...models[0], id: "c" }]))
  expect(tiers.advanced[0]?.variant).toBe("high")
  const f = routingFixture({ ...defaultSettings(), tiers })
  const ctx = {
    modelRegistry: { getAvailable: () => [...models, { ...models[0], id: "c" }] },
    sessionManager: { getBranch: () => [] },
  }
  const prepared = await prepareAdmission(
    "advanced",
    { model: f.a, reason: "user", thinkingLevel: "off", messages: [] },
    ctx,
    f.sources,
    () => [],
  )
  expect((await prepared.choose()).decision).toMatchObject({
    kind: "apply",
    model: { variant: "high" },
  })
  const result = await f.route("advanced")(
    { model: f.a, reason: "user", thinkingLevel: "off", messages: [] },
    {
      modelRegistry: { getAvailable: () => [...models, { ...models[0], id: "c" }] },
      sessionManager: { getBranch: () => [] },
    },
  )
  expect(result.thinkingLevel).toBe("high")
})
